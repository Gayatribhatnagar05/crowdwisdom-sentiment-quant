"""
Current Sentiment Outlook Module
Synthesizes current X (Twitter) sentiment dynamics, Tavily news headlines,
and multi-horizon model predictions into a concise, institutional 1-page report.
"""

import logging
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Any, List
import pandas as pd

from config import config
from src.ingestion.database import DatabaseManager

logger = logging.getLogger(__name__)


class SentimentOutlookGenerator:
    """Generates a professional 1-page sentiment outlook report for the asset."""

    def __init__(self, db_manager: DatabaseManager):
        self.db_manager = db_manager
        self.ticker = config.ticker
        self.asset_name = config.asset_name

    def generate_outlook(
        self,
        latest_features: pd.Series,
        forecasts: Dict[str, Dict[str, float]],
        backtest_metrics: Dict[str, Any]
    ) -> str:
        """
        Synthesizes metrics, news, and forecasts into a clean Markdown outlook document.
        """
        now_utc = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

        # Extract current features
        close_price = latest_features.get("close", 0.0)
        compound_weighted = latest_features.get("compound_weighted", 0.0)
        sentiment_momentum = latest_features.get("sentiment_momentum", 0.0)
        tweet_volume = int(latest_features.get("tweet_count", 0))
        vol_zscore = latest_features.get("tweet_volume_zscore", 0.0)
        pos_ratio = latest_features.get("pos_ratio", 0.0) * 100
        neg_ratio = latest_features.get("neg_ratio", 0.0) * 100
        rsi = latest_features.get("rsi_14", 0.5) * 100
        volatility = latest_features.get("volatility_24", 0.0) * 100

        # Sentiment regime determination
        if compound_weighted > 0.15 and sentiment_momentum > 0.02:
            regime = "STRONG BULLISH MOMENTUM"
            regime_color = "🟢"
            regime_desc = "High positive sentiment reinforced by expanding multi-period momentum and strong retail participation."
        elif compound_weighted > 0.05:
            regime = "MODERATE BULLISH BIAS"
            regime_color = "🟢"
            regime_desc = "Net positive retail conviction with steady engagement; watch for breakout confirmation."
        elif compound_weighted < -0.15 and sentiment_momentum < -0.02:
            regime = "BEARISH DIVERGENCE / SELLING PRESSURE"
            regime_color = "🔴"
            regime_desc = "Elevated negative chatter and bearish sentiment momentum signaling heightened downside risk."
        elif compound_weighted < -0.05:
            regime = "CAUTIOUS / DEFENSIVE"
            regime_color = "🔴"
            regime_desc = "Mild bearish bias driven by profit-taking or macro concerns; downside volatility elevated."
        else:
            regime = "NEUTRAL / CONSOLIDATION"
            regime_color = "🟡"
            regime_desc = "Balanced debate between bulls and bears; market in a range-bound state awaiting catalysts."

        # Fetch recent news
        news_df = self.db_manager.load_news(self.ticker, limit=4)
        news_bullets = []
        if not news_df.empty:
            for _, row in news_df.iterrows():
                title = row.get("title", "")
                snippet = row.get("snippet", "")
                source = row.get("source", "Tavily")
                news_bullets.append(f"- **{title}** ({source}): {snippet[:140]}...")
        else:
            news_bullets.append("- Institutional news feed currently quiet; macro data driving sentiment.")

        news_text = "\n".join(news_bullets)

        # Multi-horizon forecast rows
        forecast_rows = []
        for h, data in forecasts.items():
            ret = data.get("predicted_return_pct", 0.0)
            price = data.get("predicted_price", 0.0)
            direction = "▲" if ret >= 0 else "▼"
            forecast_rows.append(f"| **{h}** | {direction} {ret:+.2f}% | **${price:.2f}** |")

        forecast_table = "\n".join(forecast_rows)

        outlook_md = f"""# 1-Page Current Sentiment Outlook: {self.ticker} ({self.asset_name})
**Generated by CrowdWisdomTrading X Sentiment Pipeline**  
**Timestamp:** `{now_utc}` | **Current Price:** `${close_price:.2f}`

---

## 1. Executive Sentiment Summary & Regime
- **Current Sentiment Regime:** {regime_color} **{regime}**
- **Regime Context:** {regime_desc}
- **Engagement-Weighted Sentiment:** `{compound_weighted:+.3f}` (Scale: -1.0 to +1.0)
- **Sentiment Momentum (Fast vs Slow EMA):** `{sentiment_momentum:+.3f}`
- **Retail Posting Intensity:** `{tweet_volume}` tweets/interval (Rolling Z-Score: `{vol_zscore:+.2f}σ`)
- **Bullish / Bearish Post Breakdown:** `{pos_ratio:.1f}% Positive` | `{neg_ratio:.1f}% Negative` | `{100 - pos_ratio - neg_ratio:.1f}% Neutral`

---

## 2. Quantitative Multi-Horizon Price Forecasts
*Predicted price path using LightGBM model trained strictly on price and sentiment dynamics:*

| Horizon | Expected Return (%) | Target Price Forecast |
| :--- | :---: | :---: |
{forecast_table}

*Note: Horizons n+0 through n+5 represent forward steps (n is current period).*

---

## 3. Institutional News & Narrative Synthesis (via Tavily Search)
{news_text}

---

## 4. Market Microstructure & Risk Considerations
- **Price Momentum (RSI 14):** `{rsi:.1f}` (Oversold < 30, Overbought > 70)
- **Realized Volatility (24-period):** `{volatility:.2f}%`
- **Model Walk-Forward Out-of-Sample Performance:**
  - **Sharpe Ratio:** `{backtest_metrics.get('sharpe_ratio', 'N/A')}`
  - **Sortino Ratio:** `{backtest_metrics.get('sortino_ratio', 'N/A')}`
  - **Max Strategy Drawdown:** `{backtest_metrics.get('max_drawdown_pct', 'N/A')}%` (vs Benchmark MDD `{backtest_metrics.get('bnh_max_drawdown_pct', 'N/A')}%`)
  - **Win Rate:** `{backtest_metrics.get('win_rate_pct', 'N/A')}%`
- **Key Risks:** Retail sentiment spikes above +2.5σ often mark short-term exhaustion tops. Watch volume-sentiment divergence for early trend fatigue.
"""

        # Save to markdown file in project root and reports/
        out_file = config.project_root / "CURRENT_SENTIMENT_OUTLOOK.md"
        with open(out_file, "w", encoding="utf-8") as f:
            f.write(outlook_md)

        logger.info(f"Generated 1-page sentiment outlook at {out_file}")
        return outlook_md
